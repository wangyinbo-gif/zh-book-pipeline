def main():
    dirs = [x for x in sorted(os.listdir(B)) if os.path.isdir(os.path.join(B, x))]
    done, missed = [], []
    for d in dirs:
        if not os.path.exists(os.path.join(B, d, "book.json")):
            continue
        hit = None
        for key, title, author in TABLE:
            if key in d:
                hit = (title, author)
                break
        if not hit:
            missed.append(d)
            continue
        title, author = hit
        bj = os.path.join(B, d, "book.json")
        book = json.load(open(bj, encoding="utf-8"))
        book["title"] = title
        book["bookTitle"] = title
        book["author"] = author
        json.dump(book, open(bj, "w", encoding="utf-8"), ensure_ascii=False, indent=1)
        done.append((title, author))
    print("处理 %d 本，未匹配 %d 本" % (len(done), len(missed)))
    for d in missed:
        print("  !! 未匹配:", d)
    for t, a in done:
        print("  《%s》 %s" % (t, a))


if __name__ == "__main__":
    main()
