# -*- coding: utf-8 -*-
"""P2-03 + P2-09 统计口径统一 + 自动生成机制。

现场扫描 books/*/book.json + 题库，产出 reports/project_stats.json，并可用
标记块自动更新任意 README；支持发布留档快照。只用标准库，可反复重跑（幂等）。

权威口径（与 tools/booklist.py 现行定义一致，即 pipeline "chapters2" 阶段
c1_chapters.py 写入 stats.chapters 的值）：
    chapters = Σ books/*/book.json 的 stats.chapters
注意：这不是 len(book["chapters"]) 数组长度。二者历史上会分叉（见
_workbook 记录 stats考古.md），632（README/booklist）vs 636（历史 Release）
就是这条口径差 4 章所致，唯一来源是《城市意象》附录重建后数组=12 而 stats.chapters=8。

用法：
    python tools/project_stats.py                       # 仅算并写 reports/project_stats.json
    python tools/project_stats.py --readme <路径|auto>  # 再更新指定 README 标记块（auto=主区 README.md）
    python tools/project_stats.py --snapshot <tag>      # 另存 reports/snapshots/<tag>.json（拒绝覆盖）
    python tools/project_stats.py --quiet               # 只写文件少打印
"""
import argparse
import glob
import io
import json
import os
import re
import sys
import time

try:
    sys.stdout.reconfigure(encoding="utf-8", errors="replace")
    sys.stderr.reconfigure(encoding="utf-8", errors="replace")
except Exception:
    pass

# 口径版本（改统计定义时必须 +1，check_stats 依赖它识别口径）
STATS_SCHEMA_VERSION = "1.0"
RULE_VERSION = "V1.2-chapters-from-stats.chapters"

# 章节口径说明（写进 JSON.rule 供人读、供 CI 校验存在）
CHAPTER_RULE = (
    "chapters = Σ books/*/book.json:stats.chapters（= pipeline chapters2 阶段 "
    "c1_chapters.py 落盘值；书数固定为主库 books/ 下含 book.json 的目录）。"
    "不等于 Σ len(chapters[]) 数组长度——历史上《城市意象》附录重建后数组=12 而 "
    "stats.chapters=8，造成 636(数组) vs 632(stats) 的 4 章分叉。"
)

# 题库口径：同 bookId 取正式件（非 _backups/_parts/_归档）中题数最多的一份。
# 修 booklist.py 旧 glob 误吞 _backups 的脆弱点（备份件常 >= 正式件，一旦备份被
# 改数或误删就会污染总数）。这里排除备份目录，只认正式件。
BANK_EXCLUDE_DIRS = ("_backups", "_parts", "_归档")

# README 标记块锚点
BEGIN = "<!-- BEGIN PROJECT-STATS (auto-generated by tools/project_stats.py; 勿手改本块) -->"
END = "<!-- END PROJECT-STATS -->"
DATA_RE = re.compile(r"<!-- STATS-DATA (\{.*?\}) -->")


def root_from_args(arg_root):
    if arg_root:
        return arg_root
    env = os.environ.get("BOOKROOT")
    if env:
        return env
    return os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


def load_bank_counts(root):
    """返回 {bookId: 题数}，只认正式件（排除备份目录）。"""
    banks = {}
    qdir = os.path.join(root, "题库")
    for fp in glob.glob(os.path.join(qdir, "**", "*.json"), recursive=True):
        base = os.path.basename(fp)
        if base.startswith("_") or ".bak" in base:
            continue
        rel = os.path.relpath(fp, qdir).replace("\\", "/")
        parts = rel.split("/")
        if any(seg in BANK_EXCLUDE_DIRS for seg in parts[:-1]):
            continue
        try:
            with io.open(fp, encoding="utf-8") as f:
                d = json.load(f)
        except Exception:
            continue
        if not isinstance(d, dict) or not d.get("bookId"):
            continue
        n = len(d.get("questions") or [])
        if n > banks.get(d["bookId"], 0):
            banks[d["bookId"]] = n
    return banks


def compute(root):
    """核心统计：扫描 books/*/book.json + 题库 + 质检.json。幂等，除时间戳外稳定。"""
    bdir = os.path.join(root, "books")
    banks = load_bank_counts(root)

    books = []
    pages = chars = chapters = figures = paired = 0
    arr_sum = 0
    gate_pass = gate_total = gate_missing = 0
    latest_checked = ""
    bank_total = 0
    bank_sets = 0

    for dn in sorted(os.listdir(bdir)):
        bj = os.path.join(bdir, dn, "book.json")
        if not os.path.exists(bj):
            continue
        try:
            with io.open(bj, encoding="utf-8") as f:
                b = json.load(f)
        except Exception as e:
            raise SystemExit("!! book.json 解析失败: %s (%s)" % (bj, e))
        s = b.get("stats", {}) or {}
        ch_arr = b.get("chapters") or []
        pages += s.get("pages", 0) or 0
        chars += s.get("chars", 0) or 0
        chapters += s.get("chapters", 0) or 0
        figures += s.get("figures", 0) or 0
        paired += s.get("paired", 0) or 0
        arr_sum += len(ch_arr)
        qb = banks.get(dn, 0)
        if qb:
            bank_total += qb
            bank_sets += 1

        qc = os.path.join(bdir, dn, "质检.json")
        if os.path.exists(qc):
            try:
                with io.open(qc, encoding="utf-8") as f:
                    q = json.load(f)
                ok = bool((q.get("gate") or {}).get("ok"))
                gate_total += 1
                if ok:
                    gate_pass += 1
                ca = q.get("checkedAt") or ""
                if ca > latest_checked:
                    latest_checked = ca
            except Exception:
                gate_missing += 1
        else:
            gate_missing += 1

        books.append({
            "dir": dn,
            "title": b.get("bookTitle") or b.get("title") or dn,
            "shelfCategory": b.get("shelfCategory") or "扩展",
            "pages": s.get("pages", 0) or 0,
            "characters": s.get("chars", 0) or 0,
            "chapters": s.get("chapters", 0) or 0,
            "chapters_array_len": len(ch_arr),
            "figures": s.get("figures", 0) or 0,
            "paired_figures": s.get("paired", 0) or 0,
            "questions": qb,
        })

    mismatches = [x["dir"] for x in books if x["chapters"] != x["chapters_array_len"]]
    book_count = len(books)

    stats = {
        "generated_at": time.strftime("%Y-%m-%dT%H:%M:%S"),
        "stats_schema_version": STATS_SCHEMA_VERSION,
        "rule_version": RULE_VERSION,
        "rule": CHAPTER_RULE,
        "books": book_count,
        "pages": pages,
        "characters": chars,
        "chapters": chapters,
        "figures": figures,
        "paired_figures": paired,
        "questions": bank_total,
        "question_sets": bank_sets,
        "gate_status_summary": {
            "pass": gate_pass,
            "total_with_qc": gate_total,
            "missing_qc": gate_missing,
            "all_pass": (gate_pass == book_count),
            "latest_checked": latest_checked,
        },
        "diagnostics": {
            "chapters_array_sum": arr_sum,
            "chapters_stats_vs_array_delta": arr_sum - chapters,
            "chapters_field_mismatch_books": mismatches,
        },
    }
    return stats


def data_dict(stats):
    return {
        "books": stats["books"], "pages": stats["pages"],
        "characters": stats["characters"], "chapters": stats["chapters"],
        "figures": stats["figures"], "paired_figures": stats["paired_figures"],
        "questions": stats["questions"], "question_sets": stats["question_sets"],
        "gate_pass": stats["gate_status_summary"]["pass"],
        "gate_total": stats["gate_status_summary"]["total_with_qc"],
        "rule_version": stats["rule_version"],
    }


def human_block(stats):
    d = data_dict(stats)
    date = stats["generated_at"][:10]
    human = (
        "实盘规模（现算 %s）：**%s 本 / %s 页 / %s 字 / %d 章 / %s 图（配注 %s）**，"
        "全部通过程序门禁（gate %d/%d）；题库 %d 套 / %s 题（qbank.py check 0 错 0 警）。"
        % (date, d["books"], format(d["pages"], ","), format(d["characters"], ","),
           d["chapters"], format(d["figures"], ","), format(d["paired_figures"], ","),
           d["gate_pass"], d["gate_total"], d["question_sets"], format(d["questions"], ","))
    )
    return [BEGIN,
            human,
            "<!-- STATS-DATA " + json.dumps(d, ensure_ascii=False, sort_keys=True) + " -->",
            END]


def apply_readme(path, stats, bootstrap=False):
    """更新 README 标记块。有锚点=替换 BEGIN..END；无锚点且 bootstrap=True=把旧版
    「实盘规模…」自由文本行迁移成带锚点块（一次性）；两者都不满足=报错，不臆改。"""
    if not os.path.exists(path):
        raise SystemExit("!! README 不存在: %s" % path)
    with io.open(path, encoding="utf-8") as f:
        text = f.read()
    block = "\n".join(human_block(stats))
    if BEGIN in text and END in text:
        i = text.index(BEGIN)
        j = text.index(END) + len(END)
        new = text[:i] + block + text[j:]
        op = "replace"
    elif bootstrap:
        lines = text.splitlines(keepends=True)
        hit = [k for k, ln in enumerate(lines) if "实盘规模" in ln]
        if not hit:
            raise SystemExit("!! bootstrap 需要 README 有一行含「实盘规模」的旧统计行: %s" % path)
        k = hit[0]
        nl = "\n" if lines[k].endswith("\n") else ""
        lines[k:k + 1] = [block + nl]
        new = "".join(lines)
        op = "bootstrap"
    else:
        raise SystemExit("!! README 未找到统计块锚点。先手工插一次 BEGIN/END，或加 --bootstrap 迁移: %s" % path)
    changed = (new != text)
    if changed:
        with io.open(path + ".tmp", "w", encoding="utf-8", newline="\n") as f:
            f.write(new)
        os.replace(path + ".tmp", path)
    return op, changed


def write_snapshot(root, tag, stats):
    sdir = os.path.join(root, "reports", "snapshots")
    os.makedirs(sdir, exist_ok=True)
    safe = re.sub(r"[^0-9A-Za-z._-]", "_", tag)
    if not safe:
        raise SystemExit("!! 快照 tag 非法: %r" % tag)
    fp = os.path.join(sdir, safe + ".json")
    if os.path.exists(fp):
        raise SystemExit("!! 快照已存在，拒绝覆盖（发布留档不可变）: %s" % fp)
    payload = dict(stats)
    payload["snapshot_tag"] = tag
    _dump_json(fp, payload)
    return fp


def _dump_json(path, obj):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with io.open(path + ".tmp", "w", encoding="utf-8", newline="\n") as f:
        f.write(json.dumps(obj, ensure_ascii=False, indent=2, sort_keys=True) + "\n")
    os.replace(path + ".tmp", path)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--root", default=None, help="工作根（默认 BOOKROOT 或 tools/ 上一级）")
    ap.add_argument("--readme", default=None,
                    help="更新此 README 标记块；auto= <root>/README.md；不给则不动 README")
    ap.add_argument("--snapshot", default=None, metavar="TAG",
                    help="另存 reports/snapshots/<tag>.json（拒绝覆盖）")
    ap.add_argument("--bootstrap", action="store_true",
                    help="README 无锚点时，把旧「实盘规模…」自由文本行迁移为带锚点块（一次性）")
    ap.add_argument("--quiet", action="store_true")
    args = ap.parse_args()

    root = root_from_args(args.root)
    stats = compute(root)
    out = os.path.join(root, "reports", "project_stats.json")
    _dump_json(out, stats)

    if args.readme:
        rpath = os.path.join(root, "README.md") if args.readme == "auto" else args.readme
        op, changed = apply_readme(rpath, stats, bootstrap=args.bootstrap)
        if not args.quiet:
            print("README %s: %s (%s)" % (op, rpath, "已更新" if changed else "无变化"))

    if args.snapshot:
        fp = write_snapshot(root, args.snapshot, stats)
        if not args.quiet:
            print("快照写入:", fp)

    if not args.quiet:
        gs = stats["gate_status_summary"]
        dg = stats["diagnostics"]
        print("project_stats: %d 本 | 页 %s | 字 %s | 章 %d (数组和 %d, 差 %d) | 图 %s 配注 %s | 题库 %d 套 %s 题 | gate %d/%d%s"
              % (stats["books"], format(stats["pages"], ","), format(stats["characters"], ","),
                 stats["chapters"], dg["chapters_array_sum"], dg["chapters_stats_vs_array_delta"],
                 format(stats["figures"], ","), format(stats["paired_figures"], ","),
                 stats["question_sets"], format(stats["questions"], ","),
                 gs["pass"], gs["total_with_qc"],
                 ("（缺失 %d）" % gs["missing_qc"]) if gs["missing_qc"] else ""))
        if dg["chapters_field_mismatch_books"]:
            print("  warn stats.chapters != 数组长度 的书:", ", ".join(dg["chapters_field_mismatch_books"]))
    print("STATS_JSON " + json.dumps({k: stats[k] for k in
          ("books", "pages", "characters", "chapters", "figures", "paired_figures", "questions")},
          ensure_ascii=False, sort_keys=True))
    return stats


if __name__ == "__main__":
    main()
